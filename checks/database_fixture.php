<?php
declare(strict_types=1);

/** Tests ignore the runtime database unless a dedicated test DSN is explicit. */
function testMetadataConfig(array $config): array
{
    $config['database'] = ['driver' => 'sqlite', 'dsn' => '', 'table' => 'media', 'auto_create' => true];
    if ($dsn = getenv('MEDIA_BROWSER_TEST_MYSQL_DSN')) {
        $config['database'] = ['driver' => 'mysql', 'dsn' => $dsn,
            'username' => getenv('MEDIA_BROWSER_TEST_MYSQL_USER') ?: 'root',
            'password' => getenv('MEDIA_BROWSER_TEST_MYSQL_PASSWORD') ?: '',
            'table' => 'mb_check_' . bin2hex(random_bytes(6)), 'auto_create' => true];
    }
    return $config;
}

function cleanupTestMetadata(array $config): void
{
    if (($config['database']['driver'] ?? 'sqlite') === 'mysql') {
        $table = $config['database']['table'];
        if (!preg_match('/^mb_check_[a-f0-9]{12}$/D', $table)) throw new RuntimeException('Refusing to drop a table not generated by the test fixture.');
        $pdo = \MediaBrowser\Database::connect($config['database'], $config['storage']);
        $pdo->exec('DROP TABLE IF EXISTS ' . \MediaBrowser\Database::table($table));
    } elseif (is_file($config['storage'] . '/media.sqlite')) {
        unlink($config['storage'] . '/media.sqlite');
    }
}
